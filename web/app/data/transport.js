/**
 * Calculates upcoming arrivals at a stop given a reference timestamp.
 */
export function calculateArrivals(stopId, refDate = new Date()) {
  const currentMinutes = refDate.getHours() * 60 + refDate.getMinutes();
  const currentSeconds = refDate.getSeconds();

  const linesAtStop = LINES.filter((l) => l.stops.includes(stopId));
  const arrivals = [];

  for (const line of linesAtStop) {
    const freq = line.frequency_min;
    const stopSeq = line.stops.indexOf(stopId);
    let hash = 0;
    for (let i = 0; i < line.id.length; i++) {
      hash = (hash + line.id.charCodeAt(i)) % 7;
    }
    const offset = (stopSeq * 3 + hash) % freq;

    for (let k = -1; k <= 4; k++) {
      const candidateMin = Math.floor(currentMinutes / freq + k) * freq + offset;
      const diffMin = candidateMin - currentMinutes;
      const etaSec = diffMin * 60 - currentSeconds;

      if (etaSec >= -30 && etaSec <= 2700) {
        const arrTime = new Date(refDate.getTime() + etaSec * 1000);
        const hh = String(arrTime.getHours()).padStart(2, "0");
        const mm = String(arrTime.getMinutes()).padStart(2, "0");

        arrivals.push({
          line_id: line.id,
          line_name: line.name,
          line_type: line.type,
          line_color: line.color,
          headsign: line.headsign,
          scheduled_time: `${hh}:${mm}`,
          eta_seconds: Math.max(0, Math.floor(etaSec)),
          eta_minutes: Math.max(0, Math.floor(etaSec / 60)),
          status: etaSec < 60 ? "arriving" : "scheduled",
        });
      }
    }
  }

  arrivals.sort((a, b) => a.eta_seconds - b.eta_seconds);
  return arrivals.slice(0, 8);
}
